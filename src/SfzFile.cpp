namespace
{
    void put16 (juce::MemoryOutputStream& out, int value)      { out.writeShort (static_cast<short> (value)); }
    void put32 (juce::MemoryOutputStream& out, juce::uint32 value) { out.writeInt (static_cast<int> (value)); }

    /** smpl: manufacturer, product, sample period (ns), unity note, pitch fraction, SMPTE format
        and offset, how many loops, no sampler data; and the loop (forward, played for ever). */
    void putSmpl (juce::MemoryOutputStream& out, juce::uint32 rate, int rootNote, juce::int64 loopStart, juce::int64 loopEnd)
    {
        const bool looped = loopStart >= 0 && loopEnd > loopStart && loopEnd <= 0xffffffffll;
        out.write ("smpl", 4);
        put32 (out, looped ? 60u : 36u);
        put32 (out, 0);
        put32 (out, 0);
        put32 (out, static_cast<juce::uint32> (1000000000.0 / static_cast<double> (juce::jmax (1u, rate))));
        put32 (out, static_cast<juce::uint32> (juce::jlimit (0, 127, rootNote)));
        put32 (out, 0);
        put32 (out, 0);
        put32 (out, 0);
        put32 (out, looped ? 1u : 0u);
        put32 (out, 0);

        if (looped)
        {
            put32 (out, 0);                                     // cue point id
            put32 (out, 0);                                     // forward
            put32 (out, static_cast<juce::uint32> (loopStart));
            put32 (out, static_cast<juce::uint32> (loopEnd));
            put32 (out, 0);                                     // fraction
            put32 (out, 0);                                     // play count: for ever
        }
    }

    bool writeWhole (const juce::File& file, const juce::MemoryOutputStream& out)
    {
        file.getParentDirectory().createDirectory();
        juce::TemporaryFile temporary (file);

        {
            juce::FileOutputStream stream (temporary.getFile());

            if (! stream.openedOk() || ! stream.write (out.getData(), out.getDataSize()))
                return false;

            stream.flush();

            if (stream.getStatus().failed())
                return false;
        }

        return temporary.overwriteTargetFileWithTemporary();
    }
}

bool Sfz::writeWav (const juce::File& file, const juce::AudioBuffer<float>& audio, int numSamples, double sampleRate,
                    int rootNote, float gain, int bitDepth, int channels, juce::int64 loopStart, juce::int64 loopEnd)
{
    if (audio.getNumChannels() < 1)
        return false;

    numSamples = juce::jlimit (0, audio.getNumSamples(), numSamples);
    channels = juce::jlimit (1, 2, channels > 0 ? juce::jmin (channels, audio.getNumChannels()) : audio.getNumChannels());
    bitDepth = bitDepth == 16 || bitDepth == 32 ? bitDepth : 24;
    const bool isFloat = bitDepth == 32;
    const auto bytes = bitDepth / 8;
    const auto rate = static_cast<juce::uint32> (juce::roundToInt (sampleRate > 0.0 ? sampleRate : 48000.0));

    const auto dataBytes = static_cast<juce::uint64> (numSamples) * static_cast<juce::uint64> (channels) * static_cast<juce::uint64> (bytes);

    if (dataBytes > 0xffff0000ull)
        return false;   // far longer than any sample

    const auto pad = static_cast<int> (dataBytes & 1);
    const bool looped = loopStart >= 0 && loopEnd > loopStart;
    const juce::uint32 smplBytes = looped ? 60 : 36;
    const auto riffBytes = static_cast<juce::uint32> (4 + (8 + 16) + (8 + dataBytes + static_cast<juce::uint64> (pad)) + (8 + smplBytes));

    juce::MemoryOutputStream out;
    out.preallocate (static_cast<size_t> (riffBytes) + 8);

    out.write ("RIFF", 4);
    put32 (out, riffBytes);
    out.write ("WAVE", 4);

    // The plain fmt chunk: 16 bytes (PCM, or IEEE float for 32 bits).
    out.write ("fmt ", 4);
    put32 (out, 16);
    put16 (out, isFloat ? 3 : 1);
    put16 (out, channels);
    put32 (out, rate);
    put32 (out, rate * static_cast<juce::uint32> (channels * bytes));
    put16 (out, channels * bytes);
    put16 (out, bitDepth);

    out.write ("data", 4);
    put32 (out, static_cast<juce::uint32> (dataBytes));

    {
        juce::HeapBlock<char> frames (static_cast<size_t> (channels) * static_cast<size_t> (bytes) * 4096);

        for (int start = 0; start < numSamples; start += 4096)
        {
            const auto count = juce::jmin (4096, numSamples - start);
            auto* write = frames.get();

            for (int i = 0; i < count; ++i)
            {
                for (int channel = 0; channel < channels; ++channel)
                {
                    const auto raw = audio.getSample (channel, start + i) * gain;

                    if (isFloat)
                    {
                        const auto value = std::isfinite (raw) ? raw : 0.0f;
                        juce::uint32 bits = 0;
                        std::memcpy (&bits, &value, 4);
                        *write++ = static_cast<char> (bits & 0xff);
                        *write++ = static_cast<char> ((bits >> 8) & 0xff);
                        *write++ = static_cast<char> ((bits >> 16) & 0xff);
                        *write++ = static_cast<char> ((bits >> 24) & 0xff);
                        continue;
                    }

                    const auto value = juce::jlimit (-1.0f, 1.0f, std::isfinite (raw) ? raw : 0.0f);

                    if (bitDepth == 16)
                    {
                        const auto sample = juce::jlimit (-32768, 32767, static_cast<int> (std::lround (static_cast<double> (value) * 32767.0)));
                        *write++ = static_cast<char> (sample & 0xff);
                        *write++ = static_cast<char> ((sample >> 8) & 0xff);
                    }
                    else
                    {
                        const auto sample = juce::jlimit (-8388608, 8388607, static_cast<int> (std::lround (static_cast<double> (value) * 8388607.0)));
                        *write++ = static_cast<char> (sample & 0xff);
                        *write++ = static_cast<char> ((sample >> 8) & 0xff);
                        *write++ = static_cast<char> ((sample >> 16) & 0xff);
                    }
                }
            }

            out.write (frames.get(), static_cast<size_t> (write - frames.get()));
        }
    }

    if (pad != 0)
        out.writeByte (0);

    putSmpl (out, rate, rootNote, loopStart, loopEnd);
    return writeWhole (file, out);
}

bool Sfz::setWavLoop (const juce::File& wav, int rootNote, juce::int64 loopStart, juce::int64 loopEnd)
{
    juce::MemoryBlock data;

    if (! wav.loadFileAsData (data) || data.getSize() < 44)
        return false;

    const auto* raw = static_cast<const juce::uint8*> (data.getData());
    const auto size = data.getSize();

    if (std::memcmp (raw, "RIFF", 4) != 0 || std::memcmp (raw + 8, "WAVE", 4) != 0)
        return false;

    const auto read32 = [raw] (size_t at)
    {
        return static_cast<juce::uint32> (raw[at]) | (static_cast<juce::uint32> (raw[at + 1]) << 8)
             | (static_cast<juce::uint32> (raw[at + 2]) << 16) | (static_cast<juce::uint32> (raw[at + 3]) << 24);
    };

    juce::MemoryOutputStream out;
    out.write ("RIFF", 4);
    put32 (out, 0);   // its size, once it's known
    out.write ("WAVE", 4);

    juce::uint32 rate = 48000;
    bool hasFmt = false, hasData = false;

    for (size_t at = 12; at + 8 <= size;)
    {
        const auto chunkSize = read32 (at + 4);
        const auto body = at + 8;
        const auto available = static_cast<size_t> (juce::jmin<juce::uint64> (chunkSize, size - body));

        if (std::memcmp (raw + at, "fmt ", 4) == 0 && available >= 16)
        {
            // The plain 16 bytes; an extensible one's sub-format decides PCM or float.
            juce::uint8 fmt[16];
            std::memcpy (fmt, raw + body, 16);
            auto tag = static_cast<int> (fmt[0] | (fmt[1] << 8));

            if (tag == 0xfffe && available >= 26)
                tag = static_cast<int> (raw[body + 24] | (raw[body + 25] << 8));

            fmt[0] = static_cast<juce::uint8> (tag == 3 ? 3 : 1);
            fmt[1] = 0;
            rate = static_cast<juce::uint32> (fmt[4] | (fmt[5] << 8) | (fmt[6] << 16) | (fmt[7] << 24));
            out.write ("fmt ", 4);
            put32 (out, 16);
            out.write (fmt, 16);
            hasFmt = true;
        }
        else if (std::memcmp (raw + at, "data", 4) == 0)
        {
            out.write ("data", 4);
            put32 (out, static_cast<juce::uint32> (available));
            out.write (raw + body, available);

            if ((available & 1) != 0)
                out.writeByte (0);

            hasData = true;
        }
        else if (std::memcmp (raw + at, "smpl", 4) != 0 && std::memcmp (raw + at, "JUNK", 4) != 0
                 && std::memcmp (raw + at, "junk", 4) != 0 && std::memcmp (raw + at, "bext", 4) != 0
                 && std::memcmp (raw + at, "LIST", 4) != 0)
        {
            out.write (raw + at, 8 + available);

            if ((available & 1) != 0)
                out.writeByte (0);
        }

        at = body + static_cast<size_t> (chunkSize) + (chunkSize & 1);
    }

    if (! hasFmt || ! hasData)
        return false;

    putSmpl (out, rate, rootNote, loopStart, loopEnd);

    auto* written = static_cast<juce::uint8*> (const_cast<void*> (out.getData()));
    const auto riff = static_cast<juce::uint32> (out.getDataSize() - 8);
    written[4] = static_cast<juce::uint8> (riff & 0xff);
    written[5] = static_cast<juce::uint8> ((riff >> 8) & 0xff);
    written[6] = static_cast<juce::uint8> ((riff >> 16) & 0xff);
    written[7] = static_cast<juce::uint8> ((riff >> 24) & 0xff);
    return writeWhole (wav, out);
}
