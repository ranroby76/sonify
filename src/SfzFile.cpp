juce::String Sfz::text (const juce::String& name, int keys, const std::vector<Region>& regions)
{
    juce::String sfz;
    sfz << "// Auto-generated by Sonify\n";
    sfz << "// Family: " << name << "\n";
    sfz << "// Notes: " << keys << "\n\n";
    sfz << "<global>\n\n";

    for (const auto& region : regions)
    {
        sfz << "<region>\n";
        sfz << "sample=samples\\" << region.sample << "\n";
        sfz << "lokey=" << region.lokey << "\nhikey=" << region.hikey << "\n";
        sfz << "pitch_keycenter=" << region.keycenter << "\n";
        sfz << "lovel=" << region.lovel << " hivel=" << region.hivel << "\n";
        sfz << "amp_veltrack=100\n";

        if (region.seqLength > 1)
        {
            sfz << "seq_length=" << region.seqLength << "\n";
            sfz << "seq_position=" << region.seqPosition << "\n";
        }

        sfz << loopOpcodes (region.loopStart, region.loopEnd, region.loopCrossfade);
        sfz << "\n";
    }

    return sfz;
}

juce::String Sfz::builderText (const juce::String& name, const juce::String& samplesFolder, const std::vector<Region>& regions)
{
    juce::String sfz;
    sfz << "// Generated by " << name << " (Sample Builder)\n";
    sfz << "<group>\n";
    sfz << "ampeg_attack=0.001 ampeg_release=0.1\n\n";

    for (const auto& region : regions)
    {
        sfz << "<region>\n";
        sfz << "sample=" << samplesFolder << region.sample << "\n";
        sfz << "lokey=" << region.lokey << " hikey=" << region.hikey << " pitch_keycenter=" << region.keycenter << "\n";
        sfz << "lovel=" << region.lovel << " hivel=" << region.hivel << "\n";
        sfz << "amp_veltrack=100\n";

        if (region.seqLength > 1)
        {
            sfz << "seq_length=" << region.seqLength << "\n";
            sfz << "seq_position=" << region.seqPosition << "\n";
        }

        sfz << loopOpcodes (region.loopStart, region.loopEnd, region.loopCrossfade);
        sfz << "\n";
    }

    return sfz;
}

juce::String Sfz::loopOpcodes (juce::int64 loopStart, juce::int64 loopEnd, double crossfadeSeconds)
{
    if (loopStart < 0 || loopEnd <= loopStart)
        return {};

    juce::String s;
    s << "loop_mode=loop_sustain\n";
    s << "loop_start=" << juce::String (loopStart) << "\n";
    s << "loop_end=" << juce::String (loopEnd) << "\n";

    if (crossfadeSeconds >= 0.0005)
    {
        auto seconds = juce::String (crossfadeSeconds, 3);

        while (seconds.endsWithChar ('0'))
            seconds = seconds.dropLastCharacters (1);

        if (seconds.endsWithChar ('.'))
            seconds = seconds.dropLastCharacters (1);

        s << "loop_crossfade=" << seconds << "\n";
    }

    return s;
}

double Sfz::readCrossfade (const juce::String& value, double sampleRate)
{
    const auto text = value.trim();
    const auto number = text.getDoubleValue();

    if (number <= 0.0)
        return 0.0;

    if (! text.containsChar ('.') && number >= 10.0)
        return number / (sampleRate > 0.0 ? sampleRate : 44100.0);

    return juce::jmin (number, 10.0);
}

bool Sfz::writeLoopFile (const juce::File& wav, juce::int64 loopStart, juce::int64 loopEnd, int crossfade, float score)
{
    juce::String s;
    s << "loop_start=" << juce::String (loopStart) << "\nloop_end=" << juce::String (loopEnd)
      << "\ncrossfade=" << juce::String (crossfade) << "\nscore=" << juce::String (score, 4) << "\n";
    return wav.withFileExtension ("loop").replaceWithText (s);
}

bool Sfz::readLoopFile (const juce::File& wav, juce::int64& loopStart, juce::int64& loopEnd, int& crossfade)
{
    const auto file = wav.withFileExtension ("loop");

    if (! file.existsAsFile())
        return false;

    juce::String start, end, fade;

    for (const auto& line : juce::StringArray::fromLines (file.loadFileAsString()))
    {
        const auto trimmed = line.trim();

        if (trimmed.startsWith ("loop_start="))     start = trimmed.fromFirstOccurrenceOf ("=", false, false).trim();
        else if (trimmed.startsWith ("loop_end="))  end = trimmed.fromFirstOccurrenceOf ("=", false, false).trim();
        else if (trimmed.startsWith ("crossfade=")) fade = trimmed.fromFirstOccurrenceOf ("=", false, false).trim();
    }

    if (start.isEmpty() || end.isEmpty())
        return false;

    loopStart = start.getLargeIntValue();
    loopEnd = end.getLargeIntValue();
    crossfade = fade.getIntValue();
    return loopEnd > loopStart && loopStart >= 0;
}

void Sfz::removeLoopFile (const juce::File& wav)
{
    wav.withFileExtension ("loop").deleteFile();
}

bool Sfz::write (const juce::File& file, const juce::String& text)
{
    file.getParentDirectory().createDirectory();
    return file.replaceWithText (text, false, false, "\r\n");
}

