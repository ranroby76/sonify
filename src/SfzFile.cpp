juce::String Sfz::keyName (int note)
{
    static const char* const names[] { "C", "Cs", "D", "Ds", "E", "F", "Fs", "G", "Gs", "A", "As", "B" };
    note = juce::jlimit (0, 127, note);
    return juce::String (names[note % 12]) + juce::String (note / 12 - 1);
}

juce::String Sfz::safeName (const juce::String& name)
{
    static const juce::String forbidden (" :/\\*?\"<>|");
    juce::String safe;

    for (const auto c : name.trim())
        safe += (c < 32 || c == 127 || forbidden.containsChar (c)) ? static_cast<juce::juce_wchar> ('_') : c;

    // Windows drops a dot at the end of a folder's name: Piano. would be Piano.
    while (safe.endsWithChar ('.'))
        safe = safe.dropLastCharacters (1) + "_";

    return safe.isNotEmpty() ? safe : juce::String ("Sample");
}

