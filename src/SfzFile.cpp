std::vector<Sfz::Zone> Sfz::zones (const std::vector<int>& roots, int rangeLow, int rangeHigh, bool fill)
{
    std::vector<Zone> made;

    if (roots.empty())
        return made;

    const auto count = roots.size();
    made.resize (count);

    for (size_t i = 0; i < count; ++i)
    {
        auto& zone = made[i];
        zone.root = juce::jlimit (0, 127, roots[i]);

        // From 3 keys below it, but never into the zone of the key below.
        zone.low = i == 0 ? (fill ? 0 : juce::jmin (rangeLow, zone.root))
                          : juce::jmax (roots[i - 1] + 1, zone.root - 3);
    }

    for (size_t i = 0; i < count; ++i)
    {
        auto& zone = made[i];
        zone.high = i + 1 < count ? made[i + 1].low - 1
                                  : (fill ? 127 : juce::jmax (rangeHigh, zone.root));

        zone.low = juce::jlimit (0, 127, juce::jmin (zone.low, zone.root));
        zone.high = juce::jlimit (zone.root, 127, zone.high);
    }

    return made;
}

std::vector<std::pair<int, int>> Sfz::velocityRanges (const std::vector<int>& velocities)
{
    std::vector<std::pair<int, int>> ranges;
    const auto count = velocities.size();

    for (size_t v = 0; v < count; ++v)
    {
        const auto low = v == 0 ? 0 : (velocities[v - 1] + velocities[v]) / 2 + 1;
        const auto high = v + 1 == count ? 127 : (velocities[v] + velocities[v + 1]) / 2;
        ranges.emplace_back (juce::jlimit (0, 127, low), juce::jlimit (0, 127, high));
    }

    return ranges;
}

int Sfz::layerVelocity (int layer, int layers)
{
    layers = juce::jlimit (1, 127, layers);

    if (layers == 1)
        return 127;

    const auto top = juce::roundToInt (127.0 * (juce::jlimit (0, layers - 1, layer) + 1) / layers);
    return juce::jlimit (1, 127, top - 3);
}

