        /** The plugin it's the window of. */
        Host& getHost() noexcept    { return host; }

        /** The window's computer, for the preset commands' files and dialogs (nullptr: none). */
        void setDesktop (Desktop* d) noexcept    { desktop = d; presetsFound = false; }

