    // The baked window (stella_gui_data.cpp, generated by Sonify).
    enum class Kind : int { knob, slider, toggle, selector, xy, meter, lamp, scope, envelope, filter, preset, keyboard,
                            picture, custom, tabs, readout,
                            registration,     // opens Registration; 2 frames: 0 not registered, 1 registered
                            key,              // one key of a selector's set: 2 frames (0 off, 1 lit over the set in the background)
                            perform };        // a performance control (wheels, a lever, a joystick, a pad): a grid of frames

    struct Widget
    {
        Kind kind;
        int x, y, w, h;          // where its frames go (or what's drawn live), in the window's pixels
        int strip;               // its frames (see Strip); -1: none, it's drawn live
        const char* param;       // the parameter (xy: x; envelope: attack; filter: cutoff; readout: its value)
        const char* param2;      // xy: y; envelope: decay; filter: resonance
        const char* param3;      // envelope: sustain
        const char* param4;      // envelope: release
        const char* source;      // meters, lamps, scopes, programmed elements: a signal or a module display
        std::uint32_t colour;    // the accent, 0xAARRGGBB
        int vertical;            // sliders: up and down (else across)
        int count;               // selectors: positions; presets: the presets; tabs: the pages; keyboards: the
                                 // highest key (a MIDI note); custom: its place in customElements
        float threshold;         // lamps: lit from this level
        int mode;                // meters: 1 RMS, 2 a needle (added); lamps: 1 follows the level; selectors: 0 picked
                                 // across, 1 down, 2 arrows; filters: 0 LP, 1 LP24, 2 HP, 3 HP24, 4 BP;
                                 // keyboards: the lowest key
        int isDisplay;           // the source is a module display (0..1), not a signal
        float cutoffScale;       // filters: 1 if the cutoff is in Hz, 1000 in kHz, 0 to map 20 Hz..20 kHz
        int page;                // the page it's on; -1: every page
        int bx, by, bw, bh;      // where it's played: its box, upright (a slider's track, a selector's positions)
        float angle;             // its box turned about its middle, degrees clockwise

        // A key: count its number in the set; mode 0 one at a time (lit when param is min + count;
        // a click chooses it), 1 on and off by itself (param its own), 2 several at once (param's
        // bit count). A performance control: param x, param2 y; count frames across, mode frames
        // up (frame = up * count + across); vertical: 1 a pair of wheels (the left half moves x,
        // the right y), 2 x springs back to its middle when let go, 4 y does.
    };

