// The window of a plugin exported from the Plugins Creator Studio (PluginExporter), without
// JUCE. Export bakes the window: one background picture per page with everything that never
// moves, and strips of frames for what moves (a control's look at each value, a meter at each
// level, a selector at each position, the page tabs at each page, a readout at each value),
// in stella_gui_data.cpp (generated). The plugin shows a frame from those, plus what it draws
// live: scope traces, envelope and filter curves, XY dots, a keyboard's keys that are down,
// and programmed elements (stella_elements.h, when the window has any: STELLA_ELEMENTS), into
// a plain 32-bit pixel buffer that the window around it shows (stella_gui_win32.cpp on
// Windows, stella_gui_mac.mm on macOS, stella_gui_x11.cpp on Linux).
//
// A protected plugin (or one playing a protected library: Host::licenceItems isn't empty) has a
// Registration window too, drawn over the panel: the computer ID with Copy, a serial field
// (typing and Paste), Register and the result. It opens from the panel's registration badge
// (Kind::registration), or, with no badge, from a small "Demo · Register" tab in a corner
// while anything is unregistered.

#pragma once

#include <atomic>
#include <cstdint>
#include <memory>
