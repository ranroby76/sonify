    //==========================================================================
    // The window's size, as whoever plays the plugin chooses it: its baked size times a scale,
    // in steps of 5% from 50% to 200% (the Editor's size menu: a right-click; or the host's
    // window dragged bigger or smaller, snapped to the steps). Kept in the plugin's state, and
    // the last one chosen is where a new window starts (Host::windowScale).
    constexpr float minScale = 0.5f, maxScale = 2.0f, scaleStep = 0.05f;
    constexpr int numScales = 31;   // 50%, 55% ... 200%

    inline float snapScale (float scale) noexcept
    {
        if (! (scale > 0.0f))
            return 1.0f;

        const auto steps = std::lround ((scale - minScale) / scaleStep);
        return minScale + scaleStep * (float) (steps < 0 ? 0 : (steps > numScales - 1 ? numScales - 1 : steps));
    }

    inline int scaledWidth (float scale) noexcept    { const auto w = (int) std::lround ((float) width * snapScale (scale)); return w > 1 ? w : 1; }
    inline int scaledHeight (float scale) noexcept   { const auto h = (int) std::lround ((float) height * snapScale (scale)); return h > 1 ? h : 1; }

    /** The step nearest a size the host offers (the bigger of the two ways). */
    inline float scaleForSize (int w, int h) noexcept
    {
        if (width <= 0 || height <= 0)
            return 1.0f;

        const auto across = (float) w / (float) width, down = (float) h / (float) height;
        return snapScale (across > down ? across : down);
    }

